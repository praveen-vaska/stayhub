/**
 * Deterministically picks a category-matched fallback image based on a seed (e.g. property ID or slug).
 * Ensures consistency across re-renders while giving distinct properties different images.
 */
export function getAccommodationFallback(category?: string, seed?: string): string {
  const normCat = (category || "PG").trim();
  const list =
    ACCOMMODATION_FALLBACK_IMAGES[normCat] ||
    ACCOMMODATION_FALLBACK_IMAGES.Default;

  if (!seed) return list[0];

  let hash = 0;
  for (let i = 0; i < seed.length; i++) {
    hash = (hash << 5) - hash + seed.charCodeAt(i);
    hash |= 0;
  }
  const index = Math.abs(hash) % list.length;
  return list[index];
}

/**
 * Ensures an image URL is returned, defaulting to an appropriate fallback if empty or missing.
 */
export function resolvePropertyImage(
  imageSrc?: string | null,
  category?: string,
  seed?: string
): string {
  if (imageSrc && imageSrc.trim().length > 0) {
    return imageSrc;
  }
  return getAccommodationFallback(category, seed);
}
